/// Every catalog row, in registration order.
pub fn all_catalog_entries() -> &'static [StageCatalogEntry] {
    CATALOG
}

/// Exact catalog row for a canonical registered name (case-insensitive).
pub fn catalog_entry(name: &str) -> Option<&'static StageCatalogEntry> {
    let key = name.to_ascii_uppercase();
    CATALOG.iter().find(|e| e.name == key)
}

/// Resolve abbreviations through the registry, then the catalog.
pub fn catalog_lookup(verb: &str, registry: &StageRegistry) -> Option<&'static StageCatalogEntry> {
    if is_language_stage_verb(verb) {
        return None;
    }
    if let Some(e) = catalog_entry(verb) {
        return Some(e);
    }
    registry.canonical_name(verb).and_then(catalog_entry)
}

/// Default display word for a numbered connection point, if the catalog has one.
pub fn default_stream_word(
    entry: &StageCatalogEntry,
    output: bool,
    stream: u32,
) -> Option<&'static str> {
    let table = if output {
        entry.output_labels
    } else {
        entry.input_labels
    };
    table.iter().find(|(s, _)| *s == stream).map(|(_, w)| *w)
}

/// Stream numbers to draw: catalog minimum, plus any connected stream, including gaps.
pub fn streams_to_show(bounds: StreamBounds, connected: impl IntoIterator<Item = u32>) -> Vec<u32> {
    let mut n = bounds.min;
    let mut hi: Option<u32> = None;
    for s in connected {
        hi = Some(hi.map_or(s, |h| h.max(s)));
    }
    if let Some(h) = hi {
        n = n.max(h.saturating_add(1));
    }
    (0..n).collect()
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::registry::register_builtins;
    use std::collections::HashSet;

    #[test]
    fn catalog_matches_registry_names() {
        let mut reg = StageRegistry::new();
        register_builtins(&mut reg);
        let registered: HashSet<String> = reg
            .registered_names()
            .into_iter()
            .map(|s| s.to_string())
            .collect();
        let catalog: HashSet<String> = CATALOG.iter().map(|e| e.name.to_string()).collect();
        let missing: Vec<_> = registered.difference(&catalog).cloned().collect();
        let extra: Vec<_> = catalog.difference(&registered).cloned().collect();
        assert!(
            missing.is_empty() && extra.is_empty(),
            "catalog vs registry\nmissing from catalog: {missing:?}\nextra in catalog: {extra:?}"
        );
        assert_eq!(CATALOG.len(), registered.len());
    }

    #[test]
    fn catalog_help_is_plain() {
        for e in CATALOG {
            let blob = format!("{} {} {}", e.help, e.syntax, e.group.label()).to_ascii_lowercase();
            for banned in ["cms pipelines", "z/vm", "ibm", "debugger", "lane"] {
                assert!(
                    !blob.contains(banned),
                    "{} help/syntax mentions {banned}: {}",
                    e.name,
                    e.help
                );
            }
            assert!(!e.help.is_empty(), "{}", e.name);
            assert!(!e.syntax.is_empty(), "{}", e.name);
        }
    }

    #[test]
    fn locate_has_matched_unmatched_and_two_outputs() {
        let e = catalog_entry("LOCATE").unwrap();
        assert_eq!(e.group, PaletteGroup::Selection);
        assert_eq!(e.outputs.min, 1);
        assert_eq!(e.outputs.max, Some(2));
        assert_eq!(default_stream_word(e, true, 0), Some("matched"));
        assert_eq!(default_stream_word(e, true, 1), Some("unmatched"));
        let labeled = e.output_labels.iter().map(|(s, _)| *s);
        let shown = streams_to_show(e.outputs, [0].into_iter().chain(labeled));
        assert_eq!(shown, vec![0, 1]);
    }

    #[test]
    fn fanout_does_not_invent_extra_unused_outputs() {
        let e = catalog_entry("FANOUT").unwrap();
        assert_eq!(e.outputs.max, None);
        assert_eq!(streams_to_show(e.outputs, [0]), vec![0]);
        assert_eq!(streams_to_show(e.outputs, [0, 2]), vec![0, 1, 2]);
    }

    #[test]
    fn lookup_resolves_abbreviation() {
        let reg = StageRegistry::default();
        let e = catalog_lookup("CONS", &reg).expect("CONSOLE abbrev");
        assert_eq!(e.name, "CONSOLE");
        assert_eq!(e.group, PaletteGroup::DeviceDrivers);
    }

    #[test]
    fn language_stages_have_no_catalog_row() {
        let reg = StageRegistry::default();
        assert!(catalog_lookup("upper.py", &reg).is_none());
        assert!(catalog_lookup("REXX", &reg).is_none());
        assert!(is_language_stage_verb("script.rexx"));
    }

    #[test]
    fn palette_groups_include_user_buckets() {
        assert_eq!(
            PaletteGroup::MyRexxAndPython.label(),
            "My REXX and Python stages"
        );
        assert_eq!(PaletteGroup::MyPipes.label(), "My pipes");
    }
}
