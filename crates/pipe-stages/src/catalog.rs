//! Stage catalog for the GUI: palette group, stream counts, syntax, help, and
//! default stream labels.
//!
//! Inspection data only. Nothing here changes how a stage runs.

use crate::registry::StageRegistry;
use crate::topology::is_language_stage_verb;

/// Palette group for a built-in (and, later, user) stage.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum PaletteGroup {
    DeviceDrivers,
    Selection,
    FiltersAndReformatting,
    Multistream,
    MyRexxAndPython,
    MyPipes,
}

impl PaletteGroup {
    /// Heading used in the stage palette (Release 3) and Properties.
    pub fn label(self) -> &'static str {
        match self {
            Self::DeviceDrivers => "Device drivers",
            Self::Selection => "Selection",
            Self::FiltersAndReformatting => "Filters and reformatting",
            Self::Multistream => "Multistream",
            Self::MyRexxAndPython => "My REXX and Python stages",
            Self::MyPipes => "My pipes",
        }
    }
}

/// Inclusive stream count. `max` is `None` when the stage accepts any number.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct StreamBounds {
    pub min: u32,
    pub max: Option<u32>,
}

/// One built-in stage, including documented synonyms as their own rows.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct StageCatalogEntry {
    pub name: &'static str,
    pub group: PaletteGroup,
    pub inputs: StreamBounds,
    pub outputs: StreamBounds,
    pub syntax: &'static str,
    pub help: &'static str,
    pub input_labels: &'static [(u32, &'static str)],
    pub output_labels: &'static [(u32, &'static str)],
}

const NONE: &[(u32, &str)] = &[];
const MATCHED: &[(u32, &str)] = &[(0, "matched"), (1, "unmatched")];
const UNMATCHED_FIRST: &[(u32, &str)] = &[(0, "unmatched"), (1, "matched")];
const TAKEN: &[(u32, &str)] = &[(0, "taken"), (1, "rest")];
const DROPPED: &[(u32, &str)] = &[(0, "dropped"), (1, "rest")];
const IN_RANGE: &[(u32, &str)] = &[(0, "inside"), (1, "outside")];
const TRUE_FALSE: &[(u32, &str)] = &[(0, "true"), (1, "false")];
const DATA_CTRL: &[(u32, &str)] = &[(0, "data"), (1, "control")];
const BODY_PREFACE: &[(u32, &str)] = &[(0, "body"), (1, "preface")];
const BODY_APPEND: &[(u32, &str)] = &[(0, "body"), (1, "appendix")];
const LOOKUP_IN: &[(u32, &str)] = &[(0, "input"), (1, "table")];
const LOOKUP_OUT: &[(u32, &str)] = &[(0, "found"), (1, "not found"), (2, "extra")];
const MASTER_UPD: &[(u32, &str)] = &[(0, "master"), (1, "log")];
const FOUND_MISS: &[(u32, &str)] = &[(0, "ok"), (1, "other")];
const THREE_OUT: &[(u32, &str)] = &[(0, "first"), (1, "second"), (2, "third")];
const TABLE_IN: &[(u32, &str)] = &[(0, "primary"), (1, "other")];

const fn bounds(min: u32, max: Option<u32>) -> StreamBounds {
    StreamBounds { min, max }
}

const fn entry(
    name: &'static str,
    group: PaletteGroup,
    in_min: u32,
    in_max: Option<u32>,
    out_min: u32,
    out_max: Option<u32>,
    syntax: &'static str,
    help: &'static str,
    input_labels: &'static [(u32, &'static str)],
    output_labels: &'static [(u32, &'static str)],
) -> StageCatalogEntry {
    StageCatalogEntry {
        name,
        group,
        inputs: bounds(in_min, in_max),
        outputs: bounds(out_min, out_max),
        syntax,
        help,
        input_labels,
        output_labels,
    }
}

